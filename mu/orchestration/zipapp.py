"""Packaging the node agent (plan §9): ``mucli-node.pyz`` and ``install.sh``.

The zipapp contains only ``mu/orchestration/node`` (renamed ``mucli_node``) and a ``__main__``;
it needs Python 3.10+ and nothing else. It is built deterministically (fixed timestamps, sorted
entries) so its SHA-256 is stable for a given agent version, and ``install.sh`` pins that digest
and the master's TLS fingerprint. The enrolment dialog shows a one-liner that checks the
installer's own digest before running it.
"""

from __future__ import annotations

import hashlib
import io
import os
import shlex
import zipfile
from functools import lru_cache
from typing import Tuple

NODE_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "node")
_EPOCH = (2020, 1, 1, 0, 0, 0)

DEFAULT_POLICY = """\
# mucli-node local policy: the node owner's final veto (root-owned). Anything outside it is
# refused before it runs. Edit it here, or on the master's node page when allow_remote_policy
# is true (signed by the master, operator only, checked again by the root helper).
accept_categories: ["*"]          # e.g. [inventory, diagnostics, maintenance]
max_effect: read_only             # read_only | mutating | destructive
max_privilege: root               # root | unprivileged
allowed_run_as: ["*"]
allowed_tools: ["*"]              # e.g. ["sys.*", "nginx.*"]
denied_tools: []                  # e.g. ["db.*"]
require_check_mode_first: false   # changing tools must succeed in check mode here first
quiet_hours: []                   # e.g. ["Mon-Fri 09:00-17:00 Australia/Sydney"]
canary: false                     # true accepts test-signed drafts (canary nodes only)
allow_agent_updates: true         # the master may replace this agent with a signed, digest-checked
                                  # release (an update job); false: update it by hand
allow_remote_policy: true         # the operator may edit this file from the master's node page;
                                  # false: edits happen here only
"""


# The agent's own interpreter: a link the installer points at the first Python 3.10+ it finds
# (python3.13 … python3.10, then python3). The system ``python3`` is never changed: on Amazon
# Linux 2023 and RHEL 9 it is 3.9 and dnf, yum and needs-restarting depend on it.
AGENT_PYTHON = "/usr/local/lib/mucli-node/python"
PYTHON_CANDIDATES = ("python3.13", "python3.12", "python3.11", "python3.10", "python3")

UNIT = """[Unit]
Description=mucli orchestration node agent
After=network-online.target
Wants=network-online.target

[Service]
User=mucli-node
ExecStart=/usr/local/lib/mucli-node/python -I /usr/local/lib/mucli-node/mucli-node.pyz --state-dir /var/lib/mucli-node --etc-dir /etc/mucli-node run
Restart=always
RestartSec=5
ProtectHome=read-only
PrivateTmp=yes

[Install]
WantedBy=multi-user.target
"""


def _sources():
    for name in sorted(os.listdir(NODE_DIR)):
        if name.endswith(".py"):
            with open(os.path.join(NODE_DIR, name), "rb") as fh:
                yield name, fh.read()


@lru_cache(maxsize=1)
def _cached(signature: Tuple[Tuple[str, int, float], ...]) -> Tuple[bytes, str]:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        def add(path: str, data: bytes) -> None:
            info = zipfile.ZipInfo(path, date_time=_EPOCH)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            zf.writestr(info, data)

        add("__main__.py", b"import sys\nfrom mucli_node.__main__ import main\nsys.exit(main())\n")
        for name, data in _sources():
            add(f"mucli_node/{name}", data)
    data = b"#!/usr/bin/env python3\n" + buf.getvalue()
    return data, hashlib.sha256(data).hexdigest()


def build_zipapp() -> Tuple[bytes, str]:
    """(bytes, sha256 hex) of the current node agent zipapp."""
    signature = tuple((n, os.path.getsize(os.path.join(NODE_DIR, n)), os.path.getmtime(os.path.join(NODE_DIR, n)))
                      for n in sorted(os.listdir(NODE_DIR)) if n.endswith(".py"))
    return _cached(signature)


def install_script(orch, *, token: str = "", name: str = "") -> str:
    """The installer. With ``token`` (the setup wizard's download) the join token and node name
    are embedded, and a ``mucli-node.pyz`` next to the script is used instead of downloading it
    (its digest is checked either way)."""
    _data, pyz_sha = build_zipapp()
    url = orch.master_url()
    fingerprint = orch.keys.tls_identity([orch.network().get("bind") or "",
                                          orch.network().get("advertise") or ""]).display_fingerprint
    usage = "sudo bash install.sh" if token else "sudo bash install.sh --token <join token> [--name <node name>]"
    name_default = shlex.quote(name) if name else '"$(hostname)"'
    return f"""#!/bin/bash
# mucli-node installer. Generated by the mucli master; pins the agent digest and TLS fingerprint.
# Usage: {usage}
set -euo pipefail
MASTER={shlex.quote(url)}
FINGERPRINT={shlex.quote(fingerprint)}
PYZ_SHA256={shlex.quote(pyz_sha)}
TOKEN={shlex.quote(token) if token else '""'}
NAME={name_default}
while [ $# -gt 0 ]; do
  case "$1" in
    --token) TOKEN="$2"; shift 2 ;;
    --name) NAME="$2"; shift 2 ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
done
[ -n "$TOKEN" ] || {{ echo "--token is required" >&2; exit 2; }}
[ "$(id -u)" = 0 ] || {{ echo "run as root" >&2; exit 1; }}
command -v systemd-run >/dev/null || {{ echo "mucli-node needs Linux with systemd" >&2; exit 1; }}
# The agent needs Python 3.10+. Use the newest one installed and leave the system python3 alone
# (Amazon Linux 2023 / RHEL 9 ship 3.9 as python3, and dnf depends on it).
PY=""
for candidate in {" ".join(PYTHON_CANDIDATES)}; do
  path="$(command -v "$candidate" 2>/dev/null)" || continue
  if "$path" -c 'import sys; sys.exit(0 if sys.version_info >= (3, 10) else 1)' 2>/dev/null; then PY="$path"; break; fi
done
[ -n "$PY" ] || {{ echo "mucli-node needs Python 3.10 or newer, installed beside the system python3." >&2
  echo "  Amazon Linux 2023 / RHEL / Fedora: sudo dnf install python3.11" >&2
  echo "  Debian / Ubuntu: sudo apt install python3 (22.04+ ships 3.10+)" >&2; exit 1; }}

id mucli-node >/dev/null 2>&1 || useradd --system --home-dir /var/lib/mucli-node --shell /usr/sbin/nologin mucli-node
install -d -m 0755 /usr/local/lib/mucli-node /usr/local/libexec/mucli-node /etc/mucli-node
install -d -m 0700 -o mucli-node -g mucli-node /var/lib/mucli-node
install -d -m 0711 -o root -g root /var/lib/mucli-node-root
ln -sfn "$PY" {AGENT_PYTHON}
echo "mucli-node: using $PY ($("$PY" -c 'import platform; print(platform.python_version())'))"

TMP="$(mktemp)"
LOCAL_PYZ="$(dirname "$0")/mucli-node.pyz"
if [ -f "$LOCAL_PYZ" ]; then cp "$LOCAL_PYZ" "$TMP"; else curl -fsSk "$MASTER/api/orchestration/node/agent.pyz" -o "$TMP"; fi
echo "$PYZ_SHA256  $TMP" | sha256sum -c - >/dev/null || {{ echo "agent digest mismatch; refusing to install" >&2; rm -f "$TMP"; exit 1; }}
install -m 0755 -o root -g root "$TMP" /usr/local/lib/mucli-node/mucli-node.pyz
rm -f "$TMP"

cat > /usr/local/libexec/mucli-node/mucli-node-exec <<'EOF'
#!/bin/sh
exec {AGENT_PYTHON} -I /usr/local/lib/mucli-node/mucli-node.pyz exec-helper "$@"
EOF
chmod 0755 /usr/local/libexec/mucli-node/mucli-node-exec

if [ ! -f /etc/mucli-node/policy.yaml ]; then
cat > /etc/mucli-node/policy.yaml <<'EOF'
{DEFAULT_POLICY}EOF
fi
chmod 0644 /etc/mucli-node/policy.yaml

echo 'mucli-node ALL=(root) NOPASSWD: /usr/local/libexec/mucli-node/mucli-node-exec' > /etc/sudoers.d/mucli-node.tmp
chmod 0440 /etc/sudoers.d/mucli-node.tmp
visudo -cf /etc/sudoers.d/mucli-node.tmp >/dev/null && mv /etc/sudoers.d/mucli-node.tmp /etc/sudoers.d/mucli-node

{AGENT_PYTHON} -I /usr/local/lib/mucli-node/mucli-node.pyz --state-dir /var/lib/mucli-node --etc-dir /etc/mucli-node \\
  enroll --master "$MASTER" --token "$TOKEN" --fingerprint "$FINGERPRINT" --name "$NAME"
chown -R mucli-node:mucli-node /var/lib/mucli-node
chmod 0644 /etc/mucli-node/master.json

cat > /etc/systemd/system/mucli-node.service <<'EOF'
{UNIT}EOF
systemctl daemon-reload
systemctl enable --now mucli-node.service
echo "mucli-node installed and enrolled; accept it in the mucli Orchestration > Nodes page."
"""


def manual_commands(orch, token: str, name: str = "") -> list:
    """install.sh's steps one by one, for hosts where running the installer isn't wanted."""
    url = orch.master_url()
    fingerprint = orch.keys.tls_identity([orch.network().get("bind") or "",
                                          orch.network().get("advertise") or ""]).display_fingerprint
    _data, pyz_sha = build_zipapp()
    q = shlex.quote
    pyz = "/usr/local/lib/mucli-node/mucli-node.pyz"
    helper = "/usr/local/libexec/mucli-node/mucli-node-exec"
    return [
        {"title": "Check the agent you copied over", "command": f"echo '{pyz_sha}  mucli-node.pyz' | sha256sum -c -"},
        {"title": "Service user and directories",
         "command": "sudo useradd --system --home-dir /var/lib/mucli-node --shell /usr/sbin/nologin mucli-node\n"
                    "sudo install -d -m 0755 /usr/local/lib/mucli-node /usr/local/libexec/mucli-node /etc/mucli-node\n"
                    "sudo install -d -m 0700 -o mucli-node -g mucli-node /var/lib/mucli-node\n"
                    "sudo install -d -m 0711 -o root -g root /var/lib/mucli-node-root"},
        {"title": "Choose its Python (3.10 or newer, beside the system python3)",
         "command": "for c in " + " ".join(PYTHON_CANDIDATES) + "; do p=$(command -v $c) && $p -c 'import sys; sys.exit(sys.version_info < (3, 10))' "
                    f"&& {{ sudo ln -sfn $p {AGENT_PYTHON}; echo \"using $p\"; break; }}; done\n"
                    f"test -x {AGENT_PYTHON} || echo 'No Python 3.10+ found: sudo dnf install python3.11 (Amazon Linux / RHEL), then run this again'"},
        {"title": "Install the agent and its root helper",
         "command": f"sudo install -m 0755 -o root -g root mucli-node.pyz {pyz}\n"
                    f"printf '#!/bin/sh\\nexec {AGENT_PYTHON} -I {pyz} exec-helper \"$@\"\\n' | sudo tee {helper} >/dev/null\n"
                    f"sudo chmod 0755 {helper}\n"
                    f"echo 'mucli-node ALL=(root) NOPASSWD: {helper}' | sudo tee /etc/sudoers.d/mucli-node >/dev/null\n"
                    "sudo chmod 0440 /etc/sudoers.d/mucli-node && sudo visudo -cf /etc/sudoers.d/mucli-node"},
        {"title": "Local policy (read-only by default; edit it to allow more)",
         "command": "sudo tee /etc/mucli-node/policy.yaml >/dev/null <<'EOF'\n" + DEFAULT_POLICY + "EOF"},
        {"title": "Enrol with this master",
         "command": f"sudo {AGENT_PYTHON} -I {pyz} --state-dir /var/lib/mucli-node --etc-dir /etc/mucli-node enroll "
                    f"--master {q(url)} --token {q(token)} --fingerprint {q(fingerprint)} --name {q(name or 'NODE_NAME')}\n"
                    "sudo chown -R mucli-node:mucli-node /var/lib/mucli-node && sudo chmod 0644 /etc/mucli-node/master.json"},
        {"title": "Run it as a service",
         "command": "sudo tee /etc/systemd/system/mucli-node.service >/dev/null <<'EOF'\n" + UNIT + "EOF\n"
                    "sudo systemctl daemon-reload && sudo systemctl enable --now mucli-node.service"},
    ]


def install_command(orch, token: str, name: str = "") -> str:
    """The one-liner shown in the enrolment dialog (verifies the installer's digest first)."""
    url = orch.master_url()
    script = install_script(orch).encode("utf-8")
    sha = hashlib.sha256(script).hexdigest()
    name_arg = f" --name {shlex.quote(name)}" if name else ""
    return (f"curl -fsSk {url}/api/orchestration/node/install.sh -o /tmp/mucli-install.sh && "
            f"echo '{sha}  /tmp/mucli-install.sh' | sha256sum -c - && "
            f"sudo bash /tmp/mucli-install.sh --token {shlex.quote(token)}{name_arg}")
