#!/usr/bin/env python3
"""Build the Wash icon sprite (web) and icon path data (Android).

Source: mu/design/icons/*.svg (Lucide subset, ISC, 24 grid, 1.5 stroke,
plus Wash's own marks). Outputs:

* mu/gui/static/icons/wash.svg — <symbol id="i-NAME"> sprite; use with
  <svg class="w-icon"><use href="/static/icons/wash.svg#i-NAME"/></svg>
* mobile/android/src/components/icons/iconData.generated.ts — element
  lists for react-native-svg.

    python3 scripts/design/build_icons.py [--check]
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "mu/design/icons"
SPRITE = ROOT / "mu/gui/static/icons/wash.svg"
MOBILE = ROOT / "mobile/android/src/components/icons/iconData.generated.ts"
NS = "{http://www.w3.org/2000/svg}"
ALLOWED = {"path", "circle", "rect", "line", "polyline", "polygon", "ellipse"}


def icons() -> dict[str, list[tuple[str, dict]]]:
    out = {}
    for path in sorted(SRC.glob("*.svg")):
        root = ET.fromstring(path.read_text(encoding="utf-8"))
        elements = []
        for el in root.iter():
            tag = el.tag.replace(NS, "")
            if tag in ALLOWED:
                attrs = {k: v for k, v in el.attrib.items() if k != "class"}
                elements.append((tag, attrs))
        out[path.stem] = elements
    return out


def build_sprite() -> str:
    lines = [
        '<svg xmlns="http://www.w3.org/2000/svg" style="display:none">',
        "<!-- GENERATED by scripts/design/build_icons.py from mu/design/icons (Lucide ISC + Wash marks) -->",
    ]
    for name, elements in icons().items():
        lines.append(
            f'<symbol id="i-{name}" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
            'stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round">'
        )
        for tag, attrs in elements:
            attr = " ".join(f'{k}="{v}"' for k, v in attrs.items())
            lines.append(f"  <{tag} {attr}/>")
        lines.append("</symbol>")
    lines.append("</svg>")
    return "\n".join(lines) + "\n"


def _camel(key: str) -> str:
    return re.sub(r"-(\w)", lambda m: m.group(1).upper(), key)


def build_mobile() -> str:
    data = {
        name: [[tag, {_camel(k): v for k, v in attrs.items()}] for tag, attrs in elements]
        for name, elements in icons().items()
    }
    names = " | ".join(f"'{n}'" for n in data)
    return (
        "// GENERATED by scripts/design/build_icons.py — do not edit.\n"
        "// Lucide (ISC) subset + Wash marks; 24 grid, 1.5 stroke.\n\n"
        f"export type WashIconName = {names};\n\n"
        "export type IconElement = [string, Record<string, string>];\n\n"
        f"export const iconData: Record<WashIconName, IconElement[]> = {json.dumps(data, indent=2)};\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = False
    for path, content in ((SPRITE, build_sprite()), (MOBILE, build_mobile())):
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                print(f"stale: {path.relative_to(ROOT)}")
                stale = True
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
