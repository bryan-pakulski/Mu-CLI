#!/usr/bin/env python3
"""Generate web and Android token files from mu/design/*.json (Wash spec §3.2).

    python3 scripts/design/build_tokens.py          # write outputs
    python3 scripts/design/build_tokens.py --check  # exit 1 if outputs are stale

Outputs (committed, never hand-edited):

* mu/gui/static/css/wash/tokens.css      CSS custom properties, Paper + Dusk
* mu/gui/static/css/wash/hljs-wash.css   highlight.js theme from token syntax map
* mu/gui/static/js/wash_tokens.js        window.WASH (tokens + vocabulary)
* mobile/android/src/theme/wash.generated.ts
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from mu.design import (  # noqa: E402
    SEMANTICS, STEPS, THEMES, TOKENS_PATH, VOCABULARY_PATH, load_tokens, load_vocabulary,
)

CSS_OUT = ROOT / "mu/gui/static/css/wash/tokens.css"
HLJS_OUT = ROOT / "mu/gui/static/css/wash/hljs-wash.css"
JS_OUT = ROOT / "mu/gui/static/js/wash_tokens.js"
TS_OUT = ROOT / "mobile/android/src/theme/wash.generated.ts"


def source_hash() -> str:
    digest = hashlib.sha256()
    for path in (TOKENS_PATH, VOCABULARY_PATH):
        digest.update(path.read_bytes())
    return digest.hexdigest()[:16]


def header(comment: str) -> str:
    return (
        f"{comment} GENERATED by scripts/design/build_tokens.py — do not edit.\n"
        f"{comment} Source: mu/design/tokens.json + vocabulary.json (sha256 {source_hash()})\n"
    )


def _px(value: float) -> str:
    return "0" if value == 0 else f"{value}px"


def _em(value: float) -> str:
    return "0" if value == 0 else f"{value}em"


# --- web density --------------------------------------------------------------


def _round(value: float, step: float = 1.0) -> float:
    out = int(value / step + 0.5) * step
    return _num(out)


def _num(value: float) -> float:
    return int(value) if float(value).is_integer() else value


def web_scale(tokens: dict) -> dict:
    """``type``/``space``/``radius``/``size`` as the web GUI uses them: the design scale times
    ``density.web`` (text rounded to half pixels and kept at ``min_text`` or above; sizes in
    ``density.keep`` unscaled). Android uses the design scale as is."""
    density = tokens.get("density") or {}
    k = float(density.get("web", 1.0))
    if k == 1.0:
        return {name: tokens[name] for name in ("type", "space", "radius", "size")}
    floor = float(density.get("min_text", 0))
    keep = set(density.get("keep") or [])
    type_ = {}
    for name, spec in tokens["type"].items():
        size = _num(max(_round(spec["size"] * k, 0.5), min(floor, spec["size"])))
        line = max(_round(spec["line"] * k), _round(size * 1.25))
        type_[name] = dict(spec, size=size, line=line)
    return {
        "type": type_,
        "space": [max(2, _round(v * k)) for v in tokens["space"]],
        "radius": {n: v if v >= 999 else max(2, _round(v * k)) for n, v in tokens["radius"].items()},
        "size": {n: v if n in keep else _round(v * k) for n, v in tokens["size"].items()},
    }


# --- CSS ---------------------------------------------------------------------


def _theme_block(theme: str) -> list[str]:
    tokens = load_tokens()
    spec = tokens["themes"][theme]
    lines = [f"  color-scheme: {'light' if theme == 'paper' else 'dark'};"]
    for name, value in spec["color"].items():
        lines.append(f"  --wash-{name}: {value};")
    for name, steps in spec["pigment"].items():
        for step in STEPS:
            lines.append(f"  --wash-{name}-{step}: {steps[step]};")
    tint = spec["shadow"]["tint"]
    for level, value in tokens["elevation"].items():
        lines.append(f"  --wash-elevation-{level}: {value.replace('{tint}', tint)};")
    for name, value in spec.get("glass", {}).items():
        var = "--wash-glass" if name == "surface" else f"--wash-glass-{name}"
        lines.append(f"  {var}: {value};")
    for wash in tokens["glass"]["ambient"]:
        lines.append(f"  --wash-art-ambient-{wash}: url(\"/static/wash/art/ambient-{wash}-{theme}-1920.webp\");")
    lines.append(f"  --wash-art-hero: url(\"/static/wash/art/dawn-{theme}-1600.webp\");")
    lines.append(f"  --wash-art-work: url(\"/static/wash/art/lagoon-{theme}-1600.webp\");")
    lines.append(f"  --wash-art-env: url(\"/static/wash/art/meadow-{theme}-1600.webp\");")
    return lines


def _static_block() -> list[str]:
    tokens = load_tokens()
    lines = [
        f"  --wash-font-sans: {tokens['font']['sans']};",
        f"  --wash-font-mono: {tokens['font']['mono']};",
    ]
    for role in SEMANTICS:
        name = tokens["semantic"][role]
        for step in STEPS:
            lines.append(f"  --wash-{role}-{step}: var(--wash-{name}-{step});")
    lines += [
        "  --wash-neutral-wash: var(--wash-sunken);",
        "  --wash-neutral-pigment: var(--wash-ink-3);",
        "  --wash-neutral-ink: var(--wash-ink-3);",
    ]
    for mode, name in tokens["mode"].items():
        lines.append(f"  --wash-mode-{mode}: var(--wash-{name}-pigment);")
        lines.append(f"  --wash-mode-{mode}-wash: var(--wash-{name}-wash);")
        lines.append(f"  --wash-mode-{mode}-ink: var(--wash-{name}-ink);")
    for layer, name in tokens["layer"].items():
        lines.append(f"  --wash-layer-{layer}: var(--wash-{name}-pigment);")
        lines.append(f"  --wash-layer-{layer}-wash: var(--wash-{name}-wash);")
        lines.append(f"  --wash-layer-{layer}-ink: var(--wash-{name}-ink);")
    for index, name in enumerate(tokens["series"], start=1):
        lines.append(f"  --wash-series-{index}: var(--wash-{name}-pigment);")
    for role, ref in tokens["syntax"].items():
        target = f"var(--wash-{ref})" if ref.startswith("ink") else f"var(--wash-{ref}-ink)"
        lines.append(f"  --wash-syntax-{role}: {target};")
    web = web_scale(tokens)
    lines.append(f"  --wash-density: {(tokens.get('density') or {}).get('web', 1)};")
    for name, spec in web["type"].items():
        lines.append(f"  --wash-type-{name}-size: {_px(spec['size'])};")
        lines.append(f"  --wash-type-{name}-line: {_px(spec['line'])};")
        lines.append(f"  --wash-type-{name}-weight: {spec['weight']};")
        lines.append(f"  --wash-type-{name}-tracking: {_em(spec['tracking'])};")
    for index, value in enumerate(web["space"], start=1):
        lines.append(f"  --wash-space-{index}: {_px(value)};")
    for name, value in web["radius"].items():
        lines.append(f"  --wash-radius-{name}: {_px(value)};")
    for name, value in web["size"].items():
        lines.append(f"  --wash-size-{name}: {_px(value)};")
    for name, spec in tokens["motion"].items():
        lines.append(f"  --wash-motion-{name}: {spec['duration']}ms;")
        lines.append(f"  --wash-ease-{name}: {spec['easing']};")
    for name, value in tokens["z"].items():
        lines.append(f"  --wash-z-{name}: {value};")
    glass = tokens["glass"]
    lines.append(f"  --wash-glass-blur: {_px(glass['blur'])};")
    lines.append(f"  --wash-glass-blur-strong: {_px(glass['blur_strong'])};")
    lines.append(f"  --wash-glass-saturate: {glass['saturate']};")
    return lines


def build_css() -> str:
    paper = "\n".join(_theme_block("paper"))
    dusk = "\n".join(_theme_block("dusk"))
    static = "\n".join(_static_block())
    bp = load_tokens()["breakpoint"]
    return (
        header("/*").replace("/* GENERATED", "/* GENERATED").rstrip("\n").replace("\n/*", " */\n/*") + " */\n"
        + "/* Breakpoints (media queries cannot use custom properties): "
        + ", ".join(f"{k} {v}px" for k, v in bp.items()) + " */\n\n"
        + "@layer tokens {\n"
        # Aliases (semantic → pigment, mode, layer, …) are re-declared on every
        # [data-theme] scope so a nested theme (e.g. the /design gallery's
        # side-by-side panels) resolves them against its own pigments.
        + ":root,\n[data-theme] {\n" + static + "\n}\n\n"
        + ":root,\n[data-theme=\"paper\"],\n[data-theme=\"light\"] {\n" + paper + "\n}\n\n"
        + "[data-theme=\"dusk\"],\n[data-theme=\"dark\"] {\n" + dusk + "\n}\n\n"
        + "@media (prefers-color-scheme: dark) {\n  :root:not([data-theme]) {\n"
        + "\n".join("  " + line for line in _theme_block("dusk")) + "\n  }\n}\n"
        + "}\n"
    )


def build_hljs() -> str:
    rules = {
        "keyword": ".hljs-keyword, .hljs-selector-tag, .hljs-built_in, .hljs-literal, .hljs-meta .hljs-keyword",
        "string": ".hljs-string, .hljs-regexp, .hljs-addition, .hljs-attribute, .hljs-template-tag",
        "number": ".hljs-number, .hljs-symbol, .hljs-bullet, .hljs-variable.constant_",
        "function": ".hljs-title.function_, .hljs-title, .hljs-section, .hljs-name",
        "type": ".hljs-type, .hljs-title.class_, .hljs-class .hljs-title, .hljs-attr, .hljs-selector-class",
        "comment": ".hljs-comment, .hljs-quote",
        "punctuation": ".hljs-punctuation, .hljs-operator, .hljs-params",
    }
    lines = [header("/*").rstrip("\n").replace("\n/*", " */\n/*") + " */", "@layer components {"]
    lines.append(".hljs { color: var(--wash-ink); background: transparent; }")
    for role, selector in rules.items():
        extra = " font-style: italic;" if role == "comment" else ""
        lines.append(f"{selector} {{ color: var(--wash-syntax-{role});{extra} }}")
    lines.append(".hljs-deletion { color: var(--wash-danger-ink); }")
    lines.append(".hljs-emphasis { font-style: italic; }")
    lines.append(".hljs-strong { font-weight: 600; }")
    lines.append(".hljs-link { color: var(--wash-accent-ink); text-decoration: underline; }")
    lines.append("}")
    return "\n".join(lines) + "\n"


# --- JS / TS -------------------------------------------------------------------


def _flat_theme(theme: str) -> dict:
    tokens = load_tokens()
    spec = tokens["themes"][theme]
    flat = dict(spec["color"])
    for name, steps in spec["pigment"].items():
        for step in STEPS:
            flat[f"{name}-{step}"] = steps[step]
    for role in SEMANTICS:
        for step in STEPS:
            flat[f"{role}-{step}"] = spec["pigment"][tokens["semantic"][role]][step]
    flat["neutral-wash"] = spec["color"]["sunken"]
    flat["neutral-pigment"] = spec["color"]["ink-3"]
    flat["neutral-ink"] = spec["color"]["ink-3"]
    return flat


def _payload(*, web: bool = True) -> dict:
    """``web``: the density-scaled sizes the GUI uses (wash_tokens.js); Android gets the design scale."""
    tokens = load_tokens()
    scaled = web_scale(tokens) if web else {name: tokens[name] for name in ("type", "space", "radius", "size")}
    return {
        "themes": {theme: _flat_theme(theme) for theme in THEMES},
        "semantic": tokens["semantic"],
        "mode": tokens["mode"],
        "layer": tokens["layer"],
        "layerNames": tokens["layer_names"],
        "series": tokens["series"],
        "syntax": tokens["syntax"],
        "font": tokens["font"],
        "type": scaled["type"],
        "space": scaled["space"],
        "radius": scaled["radius"],
        "size": scaled["size"],
        "breakpoint": tokens["breakpoint"],
        "motion": tokens["motion"],
        "z": tokens["z"],
        "shadowTint": {theme: tokens["themes"][theme]["shadow"]["tint"] for theme in THEMES},
        "glass": {theme: tokens["themes"][theme]["glass"] for theme in THEMES},
        "glassEffect": tokens["glass"],
        "vocabulary": load_vocabulary(),
    }


def build_js() -> str:
    body = json.dumps(_payload(), indent=2, ensure_ascii=False)
    return (
        header("//")
        + "// Shared Wash tokens + status vocabulary for every web page.\n"
        + "(function (root) {\n  'use strict';\n"
        + f"  var WASH = {body.replace(chr(10), chr(10) + '  ')};\n"
        + "  WASH.stateStyle = function (state) {\n"
        + "    var key = String(state || '').split(' ')[0].toLowerCase();\n"
        + "    var v = WASH.vocabulary;\n"
        + "    var row = v.job_state[key] || v.job_status[key];\n"
        + "    var status = row ? row.status : 'pending';\n"
        + "    var spec = v.status[status] || v.status.pending;\n"
        + "    return {status: status, glyph: spec.glyph, semantic: spec.semantic,\n"
        + "            label: row ? row.label : key.replace(/_/g, ' ')};\n"
        + "  };\n"
        + "  WASH.attentionLabel = function (reason) {\n"
        + "    var row = WASH.vocabulary.attention_reason[String(reason || '')];\n"
        + "    return row ? row.label : String(reason || '').replace(/_/g, ' ');\n"
        + "  };\n"
        + "  WASH.theme = function () {\n"
        + "    var t = document.documentElement.getAttribute('data-theme');\n"
        + "    return (t === 'dusk' || t === 'dark') ? 'dusk' : 'paper';\n"
        + "  };\n"
        + "  WASH.color = function (name, theme) {\n"
        + "    return WASH.themes[theme || WASH.theme()][name];\n"
        + "  };\n"
        + "  root.WASH = WASH;\n"
        + "})(typeof window !== 'undefined' ? window : globalThis);\n"
    )


def build_ts() -> str:
    payload = _payload(web=False)
    themes = payload.pop("themes")
    vocabulary = payload.pop("vocabulary")
    lines = [header("//").rstrip("\n"), ""]
    lines.append("export type WashThemeName = 'paper' | 'dusk';")
    keys = sorted(themes["paper"])
    lines.append("export type WashColorName =\n  | " + "\n  | ".join(f"'{k}'" for k in keys) + ";")
    lines.append("export type WashPalette = Record<WashColorName, string>;")
    lines.append("")
    for theme in THEMES:
        lines.append(f"export const {theme}: WashPalette = {json.dumps(themes[theme], indent=2, ensure_ascii=False)};")
        lines.append("")
    for key, value in payload.items():
        lines.append(f"export const {key} = {json.dumps(value, indent=2, ensure_ascii=False)} as const;")
        lines.append("")
    lines.append(f"export const vocabulary = {json.dumps(vocabulary, indent=2, ensure_ascii=False)} as const;")
    lines.append("")
    return "\n".join(lines)


OUTPUTS = {CSS_OUT: build_css, HLJS_OUT: build_hljs, JS_OUT: build_js, TS_OUT: build_ts}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if outputs are stale")
    args = parser.parse_args()
    stale = []
    for path, build in OUTPUTS.items():
        content = build()
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(path)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)} — run scripts/design/build_tokens.py")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
